function producto(id, nombre, subcategoriaId, precio, descripcion, especificaciones) {
    const base = SUBCATEGORIAS[subcategoriaId];
    return {
        id,
        nombre,
        categoria: base.categoria,
        categoriaId: base.categoriaId,
        subcategoria: base.subcategoria,
        subcategoriaId,
        descripcion,
        precio,
        imagen: base.imagen,
        disponible: true,
        especificaciones: especificaciones.map(([etiqueta, valor]) => ({ nombre: etiqueta, valor }))
    };
}

